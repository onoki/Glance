import assert from 'node:assert/strict';
import { createRenderer, h } from 'vue';
let receiver;
const sent=[];
globalThis.window={external:{receiveMessage:handler=>{receiver=handler;},sendMessage:message=>sent.push(JSON.parse(message))}};
const { useWindowRole }=await import('../src/composables/useWindowRole.js');
const renderer=createRenderer({createElement:()=>({}),insert(){},remove(){},setElementText(){},patchProp(){},createText:()=>({}),createComment:()=>({}),setText(){},parentNode(){},nextSibling(){}});
let role;
const app=renderer.createApp({setup(){role=useWindowRole();return()=>h('div');}});
app.mount({});
assert.deepEqual(sent,[{type:'getWindowRole',customTitleBar:true}]);
assert.equal(role.isHelperWindow.value,false);
assert.equal(role.customTitleBar.value, false);
role.runWindowCommand('close');
assert.equal(sent.length, 1, 'commands require a Windows title bar from the host');
receiver(JSON.stringify({type:'windowRole',role:'helper'}));
assert.equal(role.isHelperWindow.value,true);
receiver(JSON.stringify({type:'zoomState',percent:100}));
assert.equal(role.isHelperWindow.value,true);
receiver(JSON.stringify({type:'windowRole',role:'main'}));
assert.equal(role.isHelperWindow.value,false);
receiver(JSON.stringify({type:'windowFrame',maximized:true,percent:125}));
assert.equal(role.customTitleBar.value,true);
assert.equal(role.maximized.value,true);
assert.equal(role.captionScale.value,0.8);
receiver(JSON.stringify({type:'zoomState',percent:200}));
assert.equal(role.captionScale.value,0.5);
const captured = new Set();
const pointer = { button: 0, buttons: 1, isPrimary: true, pointerId: 7, clientX: 10, clientY: 10, currentTarget: {
  setPointerCapture: id => captured.add(id), releasePointerCapture: id => captured.delete(id)
} };
role.beginTitleDrag(pointer);
role.moveTitleDrag({...pointer,clientX:12});
assert.equal(sent.length,1,'clicks and small pointer movements leave the window in place');
role.moveTitleDrag({...pointer,clientX:20});
role.moveTitleDrag({...pointer,clientX:30});
assert.deepEqual(sent.at(-1), {type:'windowCommand',command:'move'});
assert.equal(sent.length,2,'each drag hands off to Windows once');
assert.equal(captured.size,0);
role.runWindowCommand('toggleMaximize');
assert.deepEqual(sent.at(-1), {type:'windowCommand',command:'toggleMaximize'});
receiver(JSON.stringify({type:'windowFrame',maximized:false,percent:200}));
assert.equal(role.maximized.value,false);
app.unmount();
receiver(JSON.stringify({type:'windowRole',role:'helper'}));
assert.equal(role.isHelperWindow.value,false);
delete globalThis.window;
console.log('Desktop title bar follows native role, window state and zoom, and hands drags off once');
