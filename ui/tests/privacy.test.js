import assert from 'node:assert/strict';
import { installPrivacy, privacyMode, revealedPrivateTask } from '../src/composables/usePrivacy.js';
const hostHandlers = new Map(), docHandlers = new Map();
const host = { addEventListener: (key, fn) => hostHandlers.set(key, fn), removeEventListener: key => hostHandlers.delete(key) };
const doc = { addEventListener: (key, fn) => docHandlers.set(key, fn), removeEventListener: key => docHandlers.delete(key) };
const row = id => ({ closest: () => ({ dataset: { taskId: id } }) });
const fire = (name, id, relatedId) => docHandlers.get(name)({ target: row(id), relatedTarget: relatedId ? row(relatedId) : null });
const dispose = installPrivacy({ host, doc });
assert.equal(privacyMode.value, true, 'every new window starts protected');
fire('focusin', 'private'); assert.equal(revealedPrivateTask.value, 'private');
fire('focusout', 'private', 'private'); assert.equal(revealedPrivateTask.value, 'private', 'task controls retain task focus');
fire('focusout', 'private', 'other'); assert.equal(revealedPrivateTask.value, null);
fire('focusin', 'private'); hostHandlers.get('blur')();
assert.equal(revealedPrivateTask.value, null, 'switching to another app immediately conceals the body');
fire('focusin', 'private'); assert.equal(revealedPrivateTask.value, null, 'native focus restoration alone cannot reveal');
fire('mousedown', 'private'); fire('click', 'private'); assert.equal(revealedPrivateTask.value, 'private');
hostHandlers.get('blur')(); fire('keydown', 'private'); assert.equal(revealedPrivateTask.value, 'private', 'deliberate keyboard editing reveals');
privacyMode.value = false; assert.equal(privacyMode.value, false);
privacyMode.value = true; dispose();
assert.equal(revealedPrivateTask.value, null); assert.equal(hostHandlers.size, 0); assert.equal(docHandlers.size, 0);
console.log('Privacy: per-window default, task focus, window blur and deliberate reveal passed');
