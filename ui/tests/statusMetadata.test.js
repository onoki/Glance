import assert from 'node:assert/strict';
import { getSchema } from '@tiptap/core';
import StarterKit from '@tiptap/starter-kit';
import { StatusMetadata } from '../src/utils/statusMetadata.js';
const schema=getSchema([StarterKit,StatusMetadata]);
const legacy={type:'doc',content:[{type:'bulletList',content:[{type:'listItem',attrs:{glanceId:'old-line',statusInputAtUtc:'2026-08-01T00:00:00Z'},content:[{type:'paragraph',content:[{type:'text',text:'Keep this saved note'}]}]}]}]};
const roundtrip=schema.nodeFromJSON(legacy).toJSON();
assert.equal(roundtrip.content[0].content[0].attrs.glanceId,'old-line');
assert.equal(roundtrip.content[0].content[0].attrs.statusInputAtUtc,'2026-08-01T00:00:00Z');
assert.equal(roundtrip.content[0].content[0].content[0].content[0].text,'Keep this saved note');
console.log('Retired report metadata survives rich-document loading without report controls');
